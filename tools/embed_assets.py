#!/usr/bin/env python3
"""Embed the portable assets (out/portable/*) as C arrays for the native build.

Generates assets_embed.c / assets_embed.h consumed by native/CMakeLists.txt.
The wasm build loads the same files over HTTP; the native build links them
into the executable so the binary is a single self-contained file.

  python3 tools/embed_assets.py <out.c> <out.h>
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PORTABLE = os.path.join(ROOT, 'out', 'portable')

BIN_ASSETS = [
    ('gfx', 'gfx.bin'),
    ('levels', 'levels.bin'),
    ('cells', 'cells.bin'),
    ('overlay', 'level_overlay.bin'),
    ('screens', 'screens.bin'),
    ('mni_f1', 'mni_f1.bin'),
    ('mni_f2', 'mni_f2.bin'),
    ('mni_spl', 'mni_spl.bin'),
]


def emit_array(f, name, data):
    f.write(f'const unsigned char cc_asset_{name}[] = {{\n')
    for i in range(0, len(data), 20):
        f.write('  ' + ','.join(str(b) for b in data[i:i + 20]) + ',\n')
    f.write('};\n')
    f.write(f'const unsigned cc_asset_{name}_len = {len(data)};\n\n')


def main():
    out_c, out_h = sys.argv[1], sys.argv[2]
    with open(out_h, 'w') as f:
        f.write('/* Generated by tools/embed_assets.py - do not edit. */\n')
        f.write('#ifndef CC_ASSETS_EMBED_H\n#define CC_ASSETS_EMBED_H\n\n')
        for name, _ in BIN_ASSETS:
            f.write(f'extern const unsigned char cc_asset_{name}[];\n')
            f.write(f'extern const unsigned cc_asset_{name}_len;\n')
        f.write('extern const unsigned int cc_palette32[16];\n')
        f.write('''
typedef struct {
    int id;                     /* sound ID (1..36) */
    int ticks;                  /* trace length in 140.06 Hz driver ticks */
    const unsigned short *trace; /* ticks x 2: [PIT divisor, speaker gate] */
} cc_snd_entry;
extern const cc_snd_entry cc_snd[];
extern const int cc_snd_count;

#endif
''')

    with open(out_c, 'w') as f:
        f.write('/* Generated by tools/embed_assets.py - do not edit. */\n')
        f.write('#include "assets_embed.h"\n\n')
        for name, fname in BIN_ASSETS:
            with open(os.path.join(PORTABLE, fname), 'rb') as a:
                emit_array(f, name, a.read())

        pal = json.load(open(os.path.join(PORTABLE, 'palette.json')))
        colors = pal['colors']
        assert len(colors) == 16
        f.write('const unsigned int cc_palette32[16] = {\n')
        f.write('  ' + ', '.join(
            '0x%02X%02X%02X' % (r, g, b) for r, g, b in colors) + '\n};\n\n')

        snd = json.load(open(os.path.join(PORTABLE, 'sound.json')))
        sounds = sorted(snd['sounds'], key=lambda s: s['id'])
        f.write('typedef struct { unsigned short div, gate; } cc_tick;\n')
        for s in sounds:
            trace = s['trace']
            assert len(trace) == s['ticks']
            f.write(f'static const cc_tick cc_snd_tr_{s["id"]}[] = {{\n')
            for i in range(0, len(trace), 8):
                row = ', '.join('{%d,%d}' % (t[0], t[1]) for t in trace[i:i + 8])
                f.write('  ' + row + ',\n')
            f.write('};\n')
        f.write('const cc_snd_entry cc_snd[] = {\n')
        for s in sounds:
            f.write('  { %d, %d, (const unsigned short *)cc_snd_tr_%d },\n'
                    % (s['id'], s['ticks'], s['id']))
        f.write('};\n')
        f.write(f'const int cc_snd_count = {len(sounds)};\n')

    print(f'embed_assets: wrote {out_c} / {out_h}')


if __name__ == '__main__':
    main()
