IN_BUFF_SIZE = 0x1000
OUT_BUFF_SIZE = 0x4000  # headroom over the nominal 0x2000 window
STREAM_END = 1


class ExplodeError(Exception):
    pass


class Exploder:
    def __init__(self, data: bytes):
        self.data = data
        self.read_pos = 0
        self.in_buff = bytearray(IN_BUFF_SIZE)
        self.in_pos = 0
        self.in_bytes = 0
        self.extra_bits = 0
        self.bit_buff = 0
        self.out_buff = bytearray(OUT_BUFF_SIZE)
        self.output_pos = 0
        self.out = bytearray()
        self.ctype = 0
        self.dsize_bits = 0
        self.dsize_mask = 0
        self.LengthCodes = bytearray(0x100)
        self.DistPosCodes = bytearray(0x100)
        self.ChBitsAsc = bytearray(CH_BITS_ASC)
        self.offs2C34 = bytearray(0x100)
        self.offs2D34 = bytearray(0x100)
        self.offs2E34 = bytearray(0x100)
        self.offs2EB4 = bytearray(0x100)

    def _read_buf(self, size):
        n = min(size, len(self.data) - self.read_pos)
        chunk = self.data[self.read_pos:self.read_pos + n]
        self.read_pos += n
        return chunk, n

    def _gen_decode_tabs(self, positions, start_indexes, length_bits, elements):
        for i in range(elements):
            length = 1 << length_bits[i]
            index = start_indexes[i]
            while index < 0x100:
                positions[index] = i
                index += length

    def _gen_asc_tabs(self):
        for count in range(0xFF, -1, -1):
            bits_asc = self.ChBitsAsc[count]
            code_asc = CH_CODE_ASC[count]
            if bits_asc <= 8:
                add = 1 << bits_asc
                acc = code_asc
                while acc < 0x100:
                    self.offs2C34[acc] = count
                    acc += add
            else:
                acc = code_asc & 0xFF
                if acc != 0:
                    self.offs2C34[acc] = 0xFF
                    if code_asc & 0x3F:
                        bits_asc -= 4
                        self.ChBitsAsc[count] = bits_asc
                        add = 1 << bits_asc
                        acc = code_asc >> 4
                        while acc < 0x100:
                            self.offs2D34[acc] = count
                            acc += add
                    else:
                        bits_asc -= 6
                        self.ChBitsAsc[count] = bits_asc
                        add = 1 << bits_asc
                        acc = code_asc >> 6
                        while acc < 0x80:
                            self.offs2E34[acc] = count
                            acc += add
                else:
                    bits_asc -= 8
                    self.ChBitsAsc[count] = bits_asc
                    add = 1 << bits_asc
                    acc = code_asc >> 8
                    while acc < 0x100:
                        self.offs2EB4[acc] = count
                        acc += add

    def _waste_bits(self, nBits):
        if nBits <= self.extra_bits:
            self.extra_bits -= nBits
            self.bit_buff >>= nBits
            return 0
        self.bit_buff >>= self.extra_bits
        if self.in_pos == self.in_bytes:
            self.in_pos = IN_BUFF_SIZE
            chunk, n = self._read_buf(IN_BUFF_SIZE)
            self.in_buff[:n] = chunk
            self.in_bytes = n
            if n == 0:
                return STREAM_END
            self.in_pos = 0
        self.bit_buff |= (self.in_buff[self.in_pos] << 8)
        self.in_pos += 1
        self.bit_buff >>= (nBits - self.extra_bits)
        self.extra_bits = (self.extra_bits - nBits) + 8
        return 0

    def _decode_lit(self):
        if self.bit_buff & 1:
            if self._waste_bits(1):
                return 0x306
            length_code = self.LengthCodes[self.bit_buff & 0xFF]
            if self._waste_bits(LEN_BITS[length_code]):
                return 0x306
            extra_length_bits = EX_LEN_BITS[length_code]
            if extra_length_bits != 0:
                extra_length = self.bit_buff & ((1 << extra_length_bits) - 1)
                if self._waste_bits(extra_length_bits):
                    if (length_code + extra_length) != 0x10E:
                        return 0x306
                length_code = LEN_BASE[length_code] + extra_length
            return length_code + 0x100

        if self._waste_bits(1):
            return 0x306

        if self.ctype == CMP_BINARY:
            uncompressed_byte = self.bit_buff & 0xFF
            if self._waste_bits(8):
                return 0x306
            return uncompressed_byte

        if self.bit_buff & 0xFF:
            value = self.offs2C34[self.bit_buff & 0xFF]
            if value == 0xFF:
                if self.bit_buff & 0x3F:
                    if self._waste_bits(4):
                        return 0x306
                    value = self.offs2D34[self.bit_buff & 0xFF]
                else:
                    if self._waste_bits(6):
                        return 0x306
                    value = self.offs2E34[self.bit_buff & 0x7F]
        else:
            if self._waste_bits(8):
                return 0x306
            value = self.offs2EB4[self.bit_buff & 0xFF]

        return 0x306 if self._waste_bits(self.ChBitsAsc[value]) else value

    def _decode_dist(self, rep_length):
        dist_pos_code = self.DistPosCodes[self.bit_buff & 0xFF]
        dist_pos_bits = DIST_BITS[dist_pos_code]
        if self._waste_bits(dist_pos_bits):
            return 0
        if rep_length == 2:
            distance = (dist_pos_code << 2) | (self.bit_buff & 0x03)
            if self._waste_bits(2):
                return 0
        else:
            distance = (dist_pos_code << self.dsize_bits) | (self.bit_buff & self.dsize_mask)
            if self._waste_bits(self.dsize_bits):
                return 0
        return distance + 1

    def _expand(self):
        self.output_pos = 0x1000
        while True:
            result = next_literal = self._decode_lit()
            if result >= 0x305:
                break
            if next_literal >= 0x100:
                rep_length = next_literal - 0xFE
                minus_dist = self._decode_dist(rep_length)
                if minus_dist == 0:
                    result = 0x306
                    break
                target = self.output_pos
                source = target - minus_dist
                self.output_pos += rep_length
                for _ in range(rep_length):
                    self.out_buff[target] = self.out_buff[source]
                    target += 1
                    source += 1
            else:
                self.out_buff[self.output_pos] = next_literal
                self.output_pos += 1

            if self.output_pos >= 0x2000:
                copy_bytes = 0x1000
                self.out += self.out_buff[0x1000:0x1000 + copy_bytes]
                remaining = self.output_pos - 0x1000
                self.out_buff[0:remaining] = self.out_buff[0x1000:self.output_pos]
                self.output_pos -= 0x1000

        copy_bytes = self.output_pos - 0x1000
        self.out += self.out_buff[0x1000:0x1000 + copy_bytes]
        return result

    def explode(self):
        chunk, n = self._read_buf(IN_BUFF_SIZE)
        self.in_buff[:n] = chunk
        self.in_bytes = n
        if n <= 4:
            raise ExplodeError("input too small")
        self.ctype = self.in_buff[0]
        self.dsize_bits = self.in_buff[1]
        self.bit_buff = self.in_buff[2]
        self.extra_bits = 0
        self.in_pos = 3

        if not (4 <= self.dsize_bits <= 6):
            raise ExplodeError("invalid dictionary size %d" % self.dsize_bits)
        self.dsize_mask = 0xFFFF >> (0x10 - self.dsize_bits)

        if self.ctype != CMP_BINARY:
            if self.ctype != CMP_ASCII:
                raise ExplodeError("invalid compression mode %d" % self.ctype)
            self._gen_asc_tabs()

        self._gen_decode_tabs(self.LengthCodes, LEN_CODE, LEN_BITS, 0x10)
        self._gen_decode_tabs(self.DistPosCodes, DIST_CODE, DIST_BITS, 0x40)

        result = self._expand()
        if result != 0x306:
            return bytes(self.out)
        raise ExplodeError("decompression aborted (bad stream)")


def explode(data: bytes) -> bytes:
    return Exploder(data).explode()
