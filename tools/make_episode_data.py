#!/usr/bin/env python3
"""Generate the per-episode cell-rule constants header.

The cell-event handler code is identical between Episode 1 and Episode 2 in
every branch except the crystal pickup: the original tests the layer-3 shape
(w7) against 1..4 in Episode 1 and against 0xD..0x10 in Episode 2 (recovered
by disassembling both handlers, see notes/ep2_diff.md).  Every other pickup
and switch rule is shared.

The header is tiny and compile-time only; the values live in
tools/episode_config.py alongside the other per-episode constants.

Output: wasm/episode_data.h (episode 1), wasm/ep2_data/episode_data.h (ep2).
"""
import argparse
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

import episode_config  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description="Generate episode_data.h")
    ap.add_argument("--episode", default="ep1", help="ep1, ep2, ...")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    cfg = episode_config.get(args.episode)
    lo, hi = cfg["crystal_w7"]
    out = args.out or (
        os.path.join(ROOT, "wasm", "episode_data.h") if args.episode == "ep1"
        else os.path.join(ROOT, "wasm", args.episode + "_data", "episode_data.h"))

    lines = [
        "/* Generated by tools/make_episode_data.py for %s. */" % args.episode,
        "/* DO NOT EDIT BY HAND.  Values recovered from the original binary; */",
        "/* see notes/ep2_diff.md (cell-event crystal w7 range). */",
        "",
        "#ifndef EPISODE_DATA_H",
        "#define EPISODE_DATA_H",
        "",
        "/* Crystal pickup: w6 = 0x0D, w7 in [LO, HI]. */",
        "#define CC_EP_CRYSTAL_W7_LO 0x%02X" % lo,
        "#define CC_EP_CRYSTAL_W7_HI 0x%02X" % hi,
        "",
        "/* Segment stored in ObjectEntry.handler_seg for runtime spawns. */",
        "#define CC_EP_HANDLER_SEG 0x%04X" % cfg["handler_seg"],
        "",
        "#endif",
    ]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out, "crystal w7 0x%02X..0x%02X" % (lo, hi))


if __name__ == "__main__":
    main()
