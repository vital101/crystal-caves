#!/usr/bin/env python3
"""Generate wasm/shell_exact_data.h from the committed exactness fixtures."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FIX = os.path.join(ROOT, "notes", "shell_exactness_fixtures.json")
FLOW = os.path.join(ROOT, "notes", "shell_flow_fixtures.json")
OUT = os.path.join(ROOT, "wasm", "shell_exact_data.h")


def cstr(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        else:
            out.append(ch)
    return "".join(out)


def emit_pages(f, prefix, pages):
    for i, page in enumerate(pages):
        f.write("static const char *const %s_%d[] = {\n" % (prefix, i))
        for line in page:
            f.write('    "%s",\n' % cstr(line))
        f.write("};\n")
    f.write("static const ShellPageDef %s_pages[] = {\n" % prefix)
    for i, page in enumerate(pages):
        f.write("    { %s_%d, %d },\n" % (prefix, i, len(page)))
    f.write("};\n")
    f.write("static const int %s_page_count = %d;\n\n" % (prefix, len(pages)))


def configure(episode, out=None):
    """Point the generator at an episode's exactness fixture and header."""
    global FIX, OUT
    if episode != "ep1":
        FIX = os.path.join(ROOT, "notes", episode, "shell_exactness_fixtures.json")
    if out:
        OUT = out
    elif episode != "ep1":
        OUT = os.path.join(ROOT, "wasm", episode + "_data", "shell_exact_data.h")
    os.makedirs(os.path.dirname(OUT) or ".", exist_ok=True)


def main():
    import argparse
    ap = argparse.ArgumentParser(description="Generate shell_exact_data.h")
    ap.add_argument("--episode", default="ep1", help="ep1, ep2, ...")
    ap.add_argument("--out", default=None)
    opts = ap.parse_args()
    configure(opts.episode, opts.out)

    data = json.load(open(FIX))
    flow = data["flow"]
    attract = json.load(open(FLOW))["timing"] if os.path.exists(FLOW) else {
        "hold_ticks": 433, "scroll_rows": 200, "ticks_per_row": 2}
    hi = data["highscore"]
    keys = data["keymap"]

    with open(OUT, "w") as f:
        if opts.episode == "ep1":
            f.write("/* Generated by tools/make_shell_exact_data.py. Do not edit. */\n")
        else:
            f.write("/* Generated by tools/make_shell_exact_data.py (%s). */\n"
                    % opts.episode)
        f.write("#ifndef SHELL_EXACT_DATA_H\n#define SHELL_EXACT_DATA_H\n\n")
        f.write("typedef struct { const char *const *lines; int count; } ShellPageDef;\n\n")
        f.write("#define CC_SHELL_APOGEE_TICKS %d\n" %
                flow["timing_ticks"]["apogee"])
        f.write("#define CC_SHELL_ATTRACT_HOLD_TICKS %d\n" %
                attract["hold_ticks"])
        f.write("#define CC_SHELL_SCROLL_ROWS %d\n" % attract["scroll_rows"])
        f.write("#define CC_SHELL_SCROLL_TICKS_PER_ROW %d\n" %
                attract["ticks_per_row"])
        f.write("#define CC_SHELL_TICK_HZ %s\n\n" % flow["timing_ticks"]["tick_hz"])

        emit_pages(f, "g_intro", flow["intro_pages"])
        emit_pages(f, "g_finale", flow["finale_pages"])

        f.write("static const char *const g_hiscore_default_names[10] = {\n")
        for name in hi["defaults"]["names"]:
            f.write('    "%s",\n' % cstr(name))
        f.write("};\n")
        f.write("static const unsigned int g_hiscore_default_scores[10] = {\n")
        for score in hi["defaults"]["scores"]:
            f.write("    %du,\n" % int(score))
        f.write("};\n\n")

        f.write("static const char *const g_key_names[128] = {\n")
        for i in range(128):
            f.write('    "%s", /* %#04x */\n' %
                    (cstr(keys["names"][str(i)]), i))
        f.write("};\n\n")
        f.write("#endif\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
