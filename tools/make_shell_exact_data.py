#!/usr/bin/env python3
"""Generate wasm/shell_exact_data.h from the committed exactness fixtures."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FIX = os.path.join(ROOT, "notes", "shell_exactness_fixtures.json")
OUT = os.path.join(ROOT, "wasm", "shell_exact_data.h")


def cstr(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        else:
            out.append(ch)
    return "".join(out)


def emit_pages(f, prefix, pages):
    for i, page in enumerate(pages):
        f.write("static const char *const %s_%d[] = {\n" % (prefix, i))
        for line in page:
            f.write('    "%s",\n' % cstr(line))
        f.write("};\n")
    f.write("static const ShellPageDef %s_pages[] = {\n" % prefix)
    for i, page in enumerate(pages):
        f.write("    { %s_%d, %d },\n" % (prefix, i, len(page)))
    f.write("};\n")
    f.write("static const int %s_page_count = %d;\n\n" % (prefix, len(pages)))


def main():
    data = json.load(open(FIX))
    flow = data["flow"]
    hi = data["highscore"]
    keys = data["keymap"]

    with open(OUT, "w") as f:
        f.write("/* Generated by tools/make_shell_exact_data.py. Do not edit. */\n")
        f.write("#ifndef SHELL_EXACT_DATA_H\n#define SHELL_EXACT_DATA_H\n\n")
        f.write("typedef struct { const char *const *lines; int count; } ShellPageDef;\n\n")
        for name in ("apogee", "credits", "title"):
            f.write("#define CC_SHELL_%s_TICKS %d\n" %
                    (name.upper(), flow["timing_ticks"][name]))
        f.write("#define CC_SHELL_TICK_HZ %s\n\n" % flow["timing_ticks"]["tick_hz"])

        emit_pages(f, "g_intro", flow["intro_pages"])
        emit_pages(f, "g_finale", flow["finale_pages"])

        f.write("static const char *const g_hiscore_default_names[10] = {\n")
        for name in hi["defaults"]["names"]:
            f.write('    "%s",\n' % cstr(name))
        f.write("};\n")
        f.write("static const unsigned int g_hiscore_default_scores[10] = {\n")
        for score in hi["defaults"]["scores"]:
            f.write("    %du,\n" % int(score))
        f.write("};\n\n")

        f.write("static const char *const g_key_names[128] = {\n")
        for i in range(128):
            f.write('    "%s", /* %#04x */\n' %
                    (cstr(keys["names"][str(i)]), i))
        f.write("};\n\n")
        f.write("#endif\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
