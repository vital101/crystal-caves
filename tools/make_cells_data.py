#!/usr/bin/env python3
"""Generate the C cell data header from the golden-oracle cell dumps.

Reads notes/oracle_objects.json which contains the per-level 20-byte cell map
(column-major) produced by the real loader 0xB1A9 under Unicorn.

For each cell:
  byte 0x11 (17) = solid flag        (nonzero => blocks movement)
  byte 0x13 (19) = exit/special flag (nonzero => exit/trigger cell)

These match the original collision helper 0x1F9A:0x43 (reads byte +0x11) and
the gameplay exit check (reads byte +0x13).

Output: work/wasm/cells_data.h
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.dirname(HERE)
SRC = os.path.join(WORK, "notes", "oracle_objects.json")
DST = os.path.join(WORK, "wasm", "cells_data.h")

SRC_JSON = json.load(open(SRC))
LEVELS = sorted(SRC_JSON, key=lambda k: int(k))
MAP_COLS = 40
MAP_ROWS = 25


def cell_byte(cells_hex, row, col, offset):
    hx = cells_hex[row][col]
    return int(hx[offset * 2:offset * 2 + 2], 16)


def cell_solid(cells_hex, row, col):
    return 1 if cell_byte(cells_hex, row, col, 17) != 0 else 0


def cell_exit(cells_hex, row, col):
    return 1 if cell_byte(cells_hex, row, col, 19) != 0 else 0


def pack_column(cells_hex, row, flagfn):
    bits = 0
    for col in range(MAP_COLS):
        if flagfn(cells_hex, row, col):
            bits |= 1 << col
    return bits


def main():
    levels_solid = []
    levels_exit = []
    for lv in LEVELS:
        cells = SRC_JSON[lv]["cells"]
        grid_s = []
        grid_e = []
        for row in range(MAP_ROWS):
            grid_s.append(pack_column(cells, row, cell_solid))
            grid_e.append(pack_column(cells, row, cell_exit))
        levels_solid.append(grid_s)
        levels_exit.append(grid_e)

    def emit_table(name, levels_grid):
        lines = ["static const uint64_t %s[CELL_LEVELS][CELL_ROWS] = {" % name]
        for i, lv in enumerate(LEVELS):
            comma = "," if i < len(LEVELS) - 1 else ""
            lines.append("    {")
            for row in range(MAP_ROWS):
                c = "," if row < MAP_ROWS - 1 else ""
                lines.append("        0x%016X%s" % (levels_grid[i][row], c))
            lines.append("    }%s" % comma)
        lines.append("};")
        return lines

    lines = [
        "/* Generated by tools/make_cells_data.py from notes/oracle_objects.json. */",
        "/* DO NOT EDIT BY HAND.  Ground truth: Unicorn run of the real loader. */",
        "",
        "#ifndef CELLS_DATA_H",
        "#define CELLS_DATA_H",
        "",
        "#include \"game/cell.h\"",
        "",
        "/* Cell flags, bit-packed per row: bit col set => cell (col,row) has flag. */",
        "/* byte offset 0x11 = solid (0x13 = exit), runtime 20-byte cell record. */",
        "",
    ]
    lines += emit_table("g_cell_solid", levels_solid)
    lines.append("")
    lines += emit_table("g_cell_exit", levels_exit)
    lines.append("")
    lines.append("/* Return 1 if cell (col,row) of `level` is solid. */")
    lines.append("static int cc_cell_solid(int level, int col, int row) {")
    lines.append("    if (level < 0 || level >= CELL_LEVELS) return 1;")
    lines.append("    if (col < 0 || col >= CELL_COLS) return 1;")
    lines.append("    if (row < 0 || row >= CELL_ROWS) return 1;")
    lines.append("    return (g_cell_solid[level][row] >> col) & 1u;")
    lines.append("}")
    lines.append("")
    lines.append("/* Return 1 if cell (col,row) of `level` is an exit/trigger cell. */")
    lines.append("static int cc_cell_exit(int level, int col, int row) {")
    lines.append("    if (level < 0 || level >= CELL_LEVELS) return 0;")
    lines.append("    if (col < 0 || col >= CELL_COLS) return 0;")
    lines.append("    if (row < 0 || row >= CELL_ROWS) return 0;")
    lines.append("    return (g_cell_exit[level][row] >> col) & 1u;")
    lines.append("}")
    lines.append("")
    lines.append("#endif")
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", DST, "levels:", LEVELS)


if __name__ == "__main__":
    main()
