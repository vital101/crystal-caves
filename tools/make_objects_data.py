#!/usr/bin/env python3
"""Generate the C object data header from the golden-oracle catalog.

Reads notes/oracle_catalog.json (produced by tools/build_oracle_catalog.py
from a Unicorn run of the real loader 0xB1A9) and emits a C header with the
per-level 60-slot object image, exactly as the original binary leaves memory
after load.

Coordinate fields (x, y, x_prev, y_prev, vx, vy) are signed 16-bit: the
original uses word registers that go negative (e.g. spawn x=-41), so they must
NOT be masked to uint16_t.

Output: work/wasm/objects_data.h
"""
import hashlib
import json
import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.dirname(HERE)
SRC = os.path.join(WORK, "notes", "oracle_catalog.json")
DST = os.path.join(WORK, "wasm", "objects_data.h")

CAT = json.load(open(SRC))
LEVELS = [int(k) for k in sorted(CAT["levels"], key=lambda k: int(k))]

# Fields whose value is signed in the 8086 (word register may be negative).
SIGNED = {"x", "y", "x_prev", "y_prev", "vx", "vy"}

def s16(v):
    """Interpret an unsigned word as signed 16-bit."""
    v &= 0xFFFF
    return v - 0x10000 if v >= 0x8000 else v

# (C struct field name, oracle record key, signed?) in struct member order.
OBJ_FIELDS = [
    ("state", "state", False), ("p02", "p02", False), ("p04", "p04", False),
    ("x", "x", True), ("y", "y", True), ("x_prev", "x_prev", True),
    ("y_prev", "y_prev", True), ("tile", "tile", False),
    ("p10", "p10", False), ("p12", "p12", False), ("p14", "p14", False),
    ("p16", "p16", False), ("p18", "p18", False), ("p1a", "p1a", False),
    ("shape", "shape", False), ("vx", "p1e", True), ("vy", "p20", True),
    ("speed", "p22", False), ("p24", "p24", False),
    ("kind", "kind", False), ("ready", "ready", False),
    ("handler", "handler_off", False), ("handler_seg", "handler_seg", False),
]


def c_val(cname, ok, rec, signed):
    v = rec[ok]
    if cname == "ready":
        return "1" if v else "0"
    if signed:
        return str(s16(v))
    return str(int(v) & 0xFFFF)


def c_struct(rec):
    vals = []
    for cname, ok, signed in OBJ_FIELDS:
        vals.append(c_val(cname, ok, rec, signed))
    return "{" + ", ".join(vals) + "}"


def spawn_counts(cat):
    counts = {}
    for lv in LEVELS:
        counts[lv] = len(cat[str(lv)]["spawns"])
    return counts


def start_cells(cat):
    """Player start cell (row, col) recorded by the catalog builder."""
    starts = {}
    for lv in LEVELS:
        start = cat[str(lv)].get("start")
        if start is None:
            raise SystemExit("level %d: missing start cell in catalog" % lv)
        starts[lv] = [int(start[0]), int(start[1])]
    return starts


def main():
    cat = CAT["levels"]
    counts = spawn_counts(cat)
    starts = start_cells(cat)

    exe_sha = CAT.get("exe_sha256") if isinstance(CAT, dict) else None
    # Build a manifest hash over the catalog so data drift is detectable.
    manifest_payload = json.dumps(
        {"levels": LEVELS, "spawn_counts": counts, "starts": starts},
        sort_keys=True).encode()
    manifest = hashlib.sha256(manifest_payload).hexdigest()

    lines = [
        "/* Generated by tools/make_objects_data.py from notes/oracle_catalog.json. */",
        "/* DO NOT EDIT BY HAND.  Ground truth: Unicorn run of the real loader. */",
        "/* Manifest: %s  (hash of levels/spawn_counts/start cells) */" % manifest,
        "",
        "#ifndef OBJECTS_DATA_H",
        "#define OBJECTS_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct __attribute__((packed)) {",
        "    uint16_t state, p02, p04;",
        "    int16_t  x, y, x_prev, y_prev;",       # signed: positions may be negative
        "    uint16_t tile;",
        "    uint16_t p10, p12, p14, p16, p18, p1a, shape;",
        "    int16_t  vx, vy;",                     # signed velocity
        "    uint16_t speed, p24, kind;",
        "    uint8_t  ready;",
        "    uint16_t handler, handler_seg;",       # handler_seg is always 0x1F9A
        "} ObjectEntry;",
        "",
        "#define OBJ_MAX 60",
        "#define OBJ_LEVELS 19",
        "",
    ]
    for lv in LEVELS:
        recs = cat[str(lv)]["objects"]
        assert len(recs) == 60, (lv, len(recs))
        lines.append(f"static const ObjectEntry g_obj_level{lv}[OBJ_MAX] = {{")
        for i, rec in enumerate(recs):
            comma = "," if i < len(recs) - 1 else ""
            lines.append(f"    {c_struct(rec)}{comma}  /* slot {i} */")
        lines.append("};")
        lines.append("")
    lines.append("static const ObjectEntry *const g_obj_levels[OBJ_LEVELS] = {")
    for i, lv in enumerate(LEVELS):
        comma = "," if i < len(LEVELS) - 1 else ""
        lines.append(f"    g_obj_level{lv}{comma}")
    lines.append("};")
    lines.append("")
    lines.append("static const uint16_t g_level_cursor[OBJ_LEVELS] = {")
    for i, lv in enumerate(LEVELS):
        cursor = cat[str(lv)]["cursor"]
        comma = "," if i < len(LEVELS) - 1 else ""
        lines.append(f"    {cursor}{comma}  /* level {lv} */")
    lines.append("};")
    lines.append("")
    lines.append("/* Player start cell (row, col), from the Y-token at load time. */")
    lines.append("static const int16_t g_level_start[OBJ_LEVELS][2] = {")
    for i, lv in enumerate(LEVELS):
        r, c = starts[lv]
        comma = "," if i < len(LEVELS) - 1 else ""
        lines.append(f"    {{{r}, {c}}}{comma}  /* level {lv}: row={r} col={c} */")
    lines.append("};")
    lines.append("")
    lines.append("/* Per-level map spawn count (map-spawned objects only). */")
    lines.append("static const uint16_t g_level_spawn_count[OBJ_LEVELS] = {")
    for i, lv in enumerate(LEVELS):
        comma = "," if i < len(LEVELS) - 1 else ""
        lines.append(f"    {counts[lv]}{comma}  /* level {lv} */")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", DST, "levels:", LEVELS)
    print("manifest:", manifest)
    print("spawn_counts:", counts)


if __name__ == "__main__":
    main()
