#!/usr/bin/env python3
"""Export the Crystal Caves Sound banks and the exact tick trace.

Reads the three committed CC1-*.SND files, re-derives every playback trace,
cross-checks notes/sound_fixtures.json (produced from the real driver), and
writes:

  out/portable/sound.json       runtime metadata + per-tick traces
  wasm/sound_data.h             priority/tick-count tables for the C driver
  notes/sound_synth_fixtures.json  Python-reference synth hashes

The synth hashes are the golden reference for wasm/sound_synth.js; both use
the same integer phase/boundary math.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(HERE, "tools"))
import sound_banks as SB  # noqa: E402

OUT = os.path.join(HERE, "out", "portable")
NOTES = os.path.join(HERE, "notes")
WASM = os.path.join(HERE, "wasm")
FIXTURE = os.path.join(NOTES, "sound_fixtures.json")
SOUND_JSON = os.path.join(OUT, "sound.json")
SOUND_HDR = os.path.join(WASM, "sound_data.h")
SYNTH_FIXTURE = os.path.join(NOTES, "sound_synth_fixtures.json")
MANIFEST = os.path.join(OUT, "manifest.json")

SAMPLE_RATES = (44100, 48000)


def load_fixture():
    with open(FIXTURE) as fh:
        return json.load(fh)


def validate_against_fixture(records, fixture):
    if fixture.get("count") != len(records):
        raise SystemExit("sound fixture count mismatch")
    for rec in records:
        key = str(rec["id"])
        want = fixture["ids"].get(key)
        if not want:
            raise SystemExit("sound fixture missing id %s" % key)
        trace = SB.record_trace(rec)
        for field in ("bank", "slot", "priority", "gate"):
            if want[field] != rec[field]:
                raise SystemExit("id %s: %s mismatch" % (key, field))
        if want["ticks"] != len(trace) or want["trace"] != trace:
            raise SystemExit("id %s: trace differs from oracle fixture" % key)


def write_sound_json(records, fixture):
    doc = {
        "format": "CCSND6",
        "pit_hz": SB.PIT_HZ,
        "tick_divisor": SB.TICK_DIVISOR,
        "tick_hz": fixture["tick_hz"],
        "count": len(records),
        "sounds": [],
    }
    for rec in records:
        trace = SB.record_trace(rec)
        doc["sounds"].append({
            "id": rec["id"],
            "bank": rec["bank"],
            "slot": rec["slot"],
            "priority": rec["priority"],
            "gate": rec["gate"],
            "ticks": len(trace),
            "trace": trace,
        })
    with open(SOUND_JSON, "w") as fh:
        json.dump(doc, fh, separators=(",", ":"), sort_keys=True)
        fh.write("\n")
    return doc


def write_sound_header(records):
    n = SB.SOUND_COUNT
    bank = [0] * (n + 1)
    slot = [0] * (n + 1)
    pri = [0] * (n + 1)
    ticks = [0] * (n + 1)
    for rec in records:
        i = rec["id"]
        bank[i] = rec["bank"]
        slot[i] = rec["slot"]
        pri[i] = rec["priority"]
        ticks[i] = len(SB.record_trace(rec))
    lines = [
        "/* Generated by tools/export_sound.py; do not hand-edit. */",
        "#ifndef SOUND_DATA_H",
        "#define SOUND_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        "#define CC_SOUND_COUNT %d" % n,
        "",
        "static const uint16_t cc_sound_bank[CC_SOUND_COUNT + 1] = {",
        "    " + ", ".join(str(v) for v in bank),
        "};",
        "static const uint16_t cc_sound_slot[CC_SOUND_COUNT + 1] = {",
        "    " + ", ".join(str(v) for v in slot),
        "};",
        "static const uint16_t cc_sound_priority[CC_SOUND_COUNT + 1] = {",
        "    " + ", ".join(str(v) for v in pri),
        "};",
        "static const uint16_t cc_sound_ticks[CC_SOUND_COUNT + 1] = {",
        "    " + ", ".join(str(v) for v in ticks),
        "};",
        "",
        "#endif",
        "",
    ]
    with open(SOUND_HDR, "w") as fh:
        fh.write("\n".join(lines))


def write_synth_fixtures(records):
    doc = {
        "pit_hz": SB.PIT_HZ,
        "tick_divisor": SB.TICK_DIVISOR,
        "amplitude": 12000,
        "sample_rates": {},
    }
    for rate in SAMPLE_RATES:
        hashes = {}
        lengths = {}
        for rec in records:
            trace = SB.record_trace(rec)
            hashes[str(rec["id"])] = SB.synth_sha256(trace, rate)
            lengths[str(rec["id"])] = (
                len(trace) * rate * SB.TICK_DIVISOR) // SB.PIT_HZ
        doc["sample_rates"][str(rate)] = {
            "sha256": hashes,
            "samples": lengths,
        }
    with open(SYNTH_FIXTURE, "w") as fh:
        json.dump(doc, fh, indent=1, sort_keys=True)
        fh.write("\n")


def update_manifest(doc):
    if not os.path.exists(MANIFEST):
        return
    with open(MANIFEST) as fh:
        manifest = json.load(fh)
    manifest["sound"] = {
        "file": "sound.json",
        "format": doc["format"],
        "count": doc["count"],
        "pit_hz": doc["pit_hz"],
        "tick_divisor": doc["tick_divisor"],
        "tick_hz": doc["tick_hz"],
        "trace": "per 140.06 Hz tick: [PIT divisor, speaker on/off]",
    }
    with open(MANIFEST, "w") as fh:
        json.dump(manifest, fh, indent=2)


def main():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(WASM, exist_ok=True)
    records = SB.load_records()
    fixture = load_fixture()
    validate_against_fixture(records, fixture)
    doc = write_sound_json(records, fixture)
    write_sound_header(records)
    write_synth_fixtures(records)
    update_manifest(doc)
    print("wrote %s, %s and %s"
          % (SOUND_JSON, SOUND_HDR, SYNTH_FIXTURE))


if __name__ == "__main__":
    main()
