#!/usr/bin/env python3
"""Generate wasm/startup_data.h from notes/startup.json.

The header carries only the gameplay state the port needs: the vertical
displacement table, new-game defaults, and per-level player/camera/shape
values taken from the real loader.  It is generated data; do not edit by hand.
"""
import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "notes", "startup.json")
DST = os.path.join(ROOT, "wasm", "startup_data.h")

STARTUP_FIELDS = [
    ("a0f1", "uint16_t"), ("a0f2", "uint16_t"),
    ("a0f4", "uint16_t"), ("a0f6", "uint8_t"), ("a0f7", "uint8_t"),
    ("a0f8", "uint8_t"), ("a0fc", "uint8_t"), ("a0fd", "uint8_t"),
    ("a0ea", "uint16_t"), ("a0b4", "uint16_t"), ("a0b8", "uint16_t"),
    ("2ba", "uint16_t"), ("2ca", "uint16_t"), ("2c8", "uint16_t"),
    ("2c6", "uint16_t"), ("2e0", "uint16_t"),
    ("306", "uint8_t"), ("30a", "uint8_t"), ("30b", "uint8_t"),
    ("30c", "uint8_t"),
    ("461b", "uint16_t"), ("461d", "uint16_t"), ("461f", "uint16_t"),
    ("4619", "uint16_t"), ("4627", "uint16_t"), ("4629", "uint16_t"),
    ("460d", "uint16_t"),
    ("5118", "uint16_t"), ("5126", "uint16_t"), ("5128", "uint16_t"),
    ("5124", "uint16_t"), ("512e", "uint16_t"), ("5130", "uint16_t"),
    ("5132", "uint16_t"), ("5134", "uint16_t"),
    ("513c", "uint8_t"), ("513d", "uint8_t"), ("5140", "uint8_t"),
    ("5142", "uint8_t"),
    ("509c", "uint16_t"), ("509e", "uint16_t"),
    ("4660", "uint8_t"), ("4652", "uint16_t"),
    ("a0c0", "uint16_t"),
    # Phase 2: RNG, score, fire/timer, restart checkpoint.
    ("2a6", "uint16_t"), ("2a8", "uint16_t"), ("2da", "uint16_t"),
    ("50a5", "uint16_t"), ("50a7", "uint16_t"),
    ("50a0", "uint16_t"), ("50be", "uint16_t"), ("50c4", "uint16_t"),
    ("50c7", "uint16_t"), ("50c9", "uint16_t"),
    ("a0ff", "uint8_t"), ("a0c4", "uint16_t"),
]

LEVEL_FIELDS = [
    ("4611", "int16_t"), ("4613", "int16_t"),
    ("512e", "int16_t"), ("5130", "int16_t"),
    ("4619", "uint16_t"), ("461b", "uint16_t"), ("461d", "uint16_t"),
    ("461f", "uint16_t"), ("4627", "uint16_t"), ("4629", "uint16_t"),
    # Per-level prologue state that affects combat/fire and RNG.
    ("2da", "uint16_t"), ("2f2", "uint16_t"), ("2b8", "uint16_t"),
    ("511e", "uint16_t"), ("5122", "uint16_t"), ("30b", "uint8_t"),
    ("30d", "uint8_t"),
    ("2a6", "uint16_t"), ("2a8", "uint16_t"),
    ("50a0", "uint16_t"),
]


def main():
    data = json.load(open(SRC))
    payload = json.dumps({"table": data["table"],
                          "startup": data["startup_globals"],
                          "levels": {k: {f: v["globals"][f] for f, _ in LEVEL_FIELDS}
                                     for k, v in data["levels"].items()}},
                         sort_keys=True).encode()
    manifest = hashlib.sha256(payload).hexdigest()

    lines = [
        "/* Generated by tools/make_startup_data.py from notes/startup.json. */",
        "/* DO NOT EDIT BY HAND. */",
        "/* Manifest: %s */" % manifest,
        "/* EXE SHA-256: %s */" % data.get("exe_sha256", ""),
        "",
        "#ifndef STARTUP_DATA_H",
        "#define STARTUP_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        "/* DS:0xA111, indexed by the value of [0x5134] (0..19). */",
        "static const int8_t g_vert_speed[20] = {",
        "    " + ", ".join(str(v) for v in data["table"]),
        "};",
        "",
        "typedef struct {",
    ]
    for name, ctype in STARTUP_FIELDS:
        lines.append(f"    {ctype} f_{name};")
    lines += [
        "} cc_startup_t;",
        "",
        "static const cc_startup_t g_startup = {",
    ]
    for name, _ in STARTUP_FIELDS:
        v = data["startup_globals"][name]
        lines.append(f"    /* {name} */ {v},")
    lines += [
        "};",
        "",
        "typedef struct {",
    ]
    for name, ctype in LEVEL_FIELDS:
        lines.append(f"    {ctype} f_{name};")
    lines += [
        "} cc_level_start_t;",
        "",
        "static const cc_level_start_t g_level_start_state[19] = {",
    ]
    for lv in range(19):
        g = data["levels"][str(lv)]["globals"]
        vals = ", ".join(str(g[name]) for name, _ in LEVEL_FIELDS)
        lines.append(f"    {{ {vals} }},  /* level {lv} */")
    lines += [
        "};",
        "",
        "#endif",
    ]
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", DST, "manifest:", manifest)


if __name__ == "__main__":
    main()
